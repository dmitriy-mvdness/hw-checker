// kind_wordsgo — короткие теплые фразы, которые бот показывает студенту
// в удачные моменты: после входа, после сдачи, при 100 % прогрессе
//
// Пул выбирается случайно, состояние не храним: при пуле из ~30 фраз
// вероятность повторения подряд низкая, а антиповтор с map[int64]string
// и мьютексом не стоит овчинки Стиль: разговорный, «ты», без сюсюканья
// и без гендерных обращений — только теплое и короткое Плюс немного
// культовых киноцитат и актуального тикток-сленга 2025–2026
package handler

import "math/rand/v2"

// pickKindWord возвращает случайную фразу из пула Пустой пул — пустая
// строка: вызывающий код не должен падать math/rand/v2 в глобальном
// варианте безопасен для конкурентного использования и сеется сам,
// никаких randSeed не нужно
func pickKindWord(words []string) string {
	if len(words) == 0 {
		return ""
	}
	return words[rand.IntN(len(words))]
}


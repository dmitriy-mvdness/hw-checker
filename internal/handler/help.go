// help.go — текст справки по боту.
package handler

import "fmt"

// helpText собирает справку по боту: список команд, описание разделов,
// инструкция по сдаче ДЗ и основные правила. Используется в команде
// /help и на экране «📖 Справка».
func (h *Handler) helpText() string {
	return "📖 <b>Справка</b>\n\n" +

		"<b>Команды:</b>\n" +
		"/start — приветствие / начать заново\n" +
		"/menu — открыть главное меню\n" +
		"/help — эта справка\n\n" +

		"<b>Что умеет бот:</b>\n" +
		"📚 <b>Домашнее задание</b> — сдать ДЗ\n" +
		"📊 <b>Мои сдачи</b> — что уже сдано\n" +
		"👤 <b>Профиль</b> — информация о аккаунте и возможность выйти из него\n" +
		"✨ <b>Что нового</b> — свежие темы, в особенности новые ДЗ\n" +
		"🤝 <b>Помощь</b> — поддержка и справка\n\n" +

		"<b>Как сдать ДЗ:</b>\n" +
		"1. Открой «📚 Домашнее задание»\n" +
		"2. Выбери предмет\n" +
		"3. Выбери тему\n" +
		"4. Отправь файл сообщением\n\n" +

		"<b>Правила:</b>\n" +
		fmt.Sprintf("• Один файл до %d МБ\n", h.svc.MaxFileSizeMB()) +
		fmt.Sprintf("• Форматы: %s\n", h.svc.AllowedExtsDisplay()) +
		fmt.Sprintf("• На одну тему — до %d попыток\n\n", h.svc.MaxSubmissions()) +

		"<i>Если что-то не работает — напиши в «🛠️ Техподдержка»</i>"

}
